#!/usr/bin/env python3
"""Replay every finite group certificate; no random search and no third-party deps.
Run beside audit_verify.py: python3 check_certificates.py audit_results.json
The state order is lexicographic; B/R act on the left, word symbols 0/1/2/3
mean B/R/B^-1/R^-1, applied successively from left to right.
"""
import collections, json, math, pathlib, sys
from audit_verify import B, words, inverse, cycles, eccentricity, minimal_congruence, vectors

data=json.loads(pathlib.Path(sys.argv[1] if len(sys.argv)>1 else 'audit_results.json').read_text())
assert [tuple(r['p']) for r in data['groups']] == vectors(3,500)
counts=collections.Counter()
for row in data['groups']:
    ws=words(row['p']); ix={w:i for i,w in enumerate(ws)}; n=len(ws)
    gens=[[ix[B(w)] for w in ws],[ix[w[1:]+w[:1]] for w in ws]]
    assert n==row['N'] and all(sorted(g)==list(range(n)) for g in gens)
    assert eccentricity(gens)==(row['fwd'],n)
    assert eccentricity(gens+[inverse(g) for g in gens])[0]==row['sym']
    parities=[(n-len(cycles(g)))%2 for g in gens]
    assert parities==row['parity']
    cls=row['classification']; counts[cls]+=1
    if cls=='imprimitive':
        blocks=row['blocks']; labels={i:j for j,c in enumerate(blocks) for i in c}
        assert sorted(labels)==list(range(n))
        assert len(set(map(len,blocks)))==1 and 1<len(blocks)<n
        for g in gens:
            assert all(len({labels[g[i]] for i in c})==1 for c in blocks)
    else:
        assert cls in ['S','A']
        # In a transitive action every nontrivial block through 0 contains j!=0.
        # The least invariant equivalence generated by 0~j must be universal.
        for j in range(1,n):
            assert len(set(minimal_congruence(gens,j)))==1
        cert=row['jordan']; gs=gens+[inverse(g) for g in gens]; p=list(range(n))
        for k in cert['word']: p=[gs[k][v] for v in p]
        cs=cycles(p)
        assert [len(c) for c in cs]==cert['cycle_lengths']
        q=cert['prime']; power=cert['power']
        assert 2<=q<=n-3 and all(q%d for d in range(2,math.isqrt(q)+1))
        powered=list(range(n))
        for c in cs:
            for j,v in enumerate(c): powered[v]=c[(j+power)%len(c)]
        assert [len(c) for c in cycles(powered) if len(c)>1]==[q]
        assert cls==('S' if any(parities) else 'A')
assert dict(counts)==data['group_counts']
print('PASS: 113 classifications; exact invariant blocks / primitive closures;')
print('74 replayed single-prime-cycle Jordan witnesses; generator parities; BFS depths.')
print(dict(counts))
